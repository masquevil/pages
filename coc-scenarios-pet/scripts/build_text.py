"""同步 Markdown 文案至无需网络请求的浏览器脚本。"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sections(text: str) -> dict:
    result = {}
    for match in re.finditer(r'^### (cover|\d{2}) ([^\n]+)\n(.*?)(?=^### |\Z)', text, re.M | re.S):
        result[match[1]] = {
            'label': match[2],
            'paragraphs': [p.strip() for p in match[3].strip().split('\n\n') if p.strip()],
        }
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = (ROOT / 'docs/绘本文本.md').read_text()
    common = text.split('## 2. 分页制作模板')[1].split('## 3.')[0]
    birds = text.split('## 3. 鸟类整页覆盖文案')[1].split('### 画面配合说明')[0]
    data = {'common': sections(common), 'birds': sections(birds)}
    output = '// Generated by scripts/build_text.py; edit docs/绘本文本.md instead.\n'
    output += 'globalThis.BookText = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    target = ROOT / 'picture-book/js/data.js'
    if args.check:
        if target.read_text() != output:
            raise SystemExit('data.js 与绘本文本.md 不一致，请运行 build_text.py')
        print('文案同步检查通过')
    else:
        target.write_text(output)


if __name__ == '__main__':
    main()